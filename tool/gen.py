#!/usr/bin/env python3
# protoc-gen-easyrpc-python: emit <file>_easyrpc_pb2.py strong-typed client.
#
# Package-aware: the message import path and client class name are derived from
# the proto, so any package (e.g. agent.v1) is generated instead of hard-coding
# conformance. EASYRPC_PY_LIB controls the generated cross-package library root
# (default 'easyrpc').
import os
import sys
from google.protobuf.compiler import plugin_pb2 as plugin


def resolve(f):
    out = []
    pkg = f.package or ''
    for svc in f.service:
        for m in svc.method:
            path = rest_path(m) or f'/{pkg}.{svc.name}/{m.name}'
            out.append((svc.name, m.name or '', path, m.server_streaming,
                        m.input_type.split('.')[-1], m.output_type.split('.')[-1]))
    return out


def rest_path(m):
    opts = m.options
    if not opts:
        return None
    try:
        raw = opts.SerializeToString()
        pos = 0
        while pos < len(raw):
            tag, pos = readvar(raw, pos)
            field = tag >> 3
            wt = tag & 7
            if wt == 2:
                ln, pos = readvar(raw, pos)
                val = raw[pos:pos + ln]
                pos += ln
                if field == 72295728:
                    p = parse_rule(val)
                    if p:
                        return p
            elif wt == 0:
                _, pos = readvar(raw, pos)
            elif wt == 5:
                pos += 4
            elif wt == 1:
                pos += 8
    except Exception:
        return None
    return None


def readvar(b, i):
    v = 0
    s = 0
    while True:
        x = b[i] if i < len(b) else 0
        i += 1
        v |= (x & 0x7f) << s
        s += 7
        if not x & 0x80:
            break
    return v, i


def parse_rule(d):
    i = 0
    while i < len(d):
        tag, i = readvar(d, i)
        field = tag >> 3
        wt = tag & 7
        if wt == 2:
            ln, i = readvar(d, i)
            val = d[i:i + ln].decode()
            i += ln
            if field in (2, 4, 3, 6):
                return val
        elif wt == 0:
            _, i = readvar(d, i)
        elif wt == 5:
            i += 4
        elif wt == 1:
            i += 8
    return None


def main():
    data = sys.stdin.buffer.read()
    req = plugin.CodeGeneratorRequest.FromString(data)
    lib = os.environ.get('EASYRPC_PY_LIB', 'easyrpc')
    # Message module: <lib>.<pkg dirs>/<base>_pb2, with '.' -> '_'.
    files = []
    for f in req.proto_file:
        if f.name not in req.file_to_generate:
            continue
        ms = resolve(f)
        if not ms:
            continue
        base = f.name[:-6]                       # strip .proto (incl dirs)
        pkg_dir = os.path.dirname(f.name).replace('\\', '/')
        parts = pkg_dir.split('/') if pkg_dir else []
        if parts and parts[0] == lib:
            parts = parts[1:]
        pkg_dir = '/'.join(parts)
        # protobuf module segments use underscore for dots in package, but path keeps '/' so we keep dirs as-is and only sanitize final module.
        pkg_dir = pkg_dir.replace('.', '_')
        mod_base = os.path.basename(base)
        # Avoid duplicating the library segment when the proto path already starts with it.
        if pkg_dir.split('.')[0] == lib:
            mod_path = f"{pkg_dir}/{mod_base}_pb2"
        else:
            mod_path = f"{lib}.{pkg_dir}/{mod_base}_pb2" if pkg_dir else f"{lib}.{mod_base}_pb2"
        mod_path = mod_path.replace('/', '.')
        for (svc, _n, _p, _s, _i, _o) in ms:
            client = svc + 'Client'
        L = ['# Code generated by protoc-gen-easyrpc-python. DO NOT EDIT.',
             'from easyrpc import Transport, Request',
             f'from {mod_path} import * as m',
             'import asyncio', '',
             f'class {client}:',
             '    def __init__(self, transport: Transport): self._t = transport', '']
        for (svc, name, path, ss, it, ot) in ms:
            if ss:
                L.append('    async def %s(self, req: m.%s) -> "AsyncIterator[m.%s]":' % (camel(name), it, ot))
                L.append('        st = await self._t.open_stream(Request(url="%s", body=req.SerializeToString()))' % path)
                L.append('        async for chunk in st: yield m.%s.FromString(chunk)' % ot)
                L.append('')
            else:
                L.append('    async def %s(self, req: m.%s) -> m.%s:' % (camel(name), it, ot))
                L.append('        res = await self._t.send(Request(url="%s", body=req.SerializeToString()))' % path)
                L.append('        if res.error: raise res.error')
                L.append('        return m.%s.FromString(res.body)' % ot)
                L.append('')
        content = '\n'.join(L)
        files.append(plugin.CodeGeneratorResponse.File(name=base + '_easyrpc_pb2.py', content=content))
    resp = plugin.CodeGeneratorResponse(file=files)
    sys.stdout.buffer.write(resp.SerializeToString())


def camel(s):
    return s[:1].lower() + s[1:]


if __name__ == '__main__':
    main()
