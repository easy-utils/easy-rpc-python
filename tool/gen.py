#!/usr/bin/env python3
# protoc-gen-easyrpc-python: read CodeGeneratorRequest, emit <file>_easyrpc_pb2.py
# containing a method table + strong-typed client harness. Uses google.protobuf.
import sys, os
from google.protobuf.compiler import plugin_pb2 as plugin
from google.protobuf import descriptor_pb2 as desc
from google.protobuf.descriptor_pb2 import MethodOptions

def varint(b,i):
    v=0;s=0
    while True:
        x=b[i];i+=1;v|=(x&0x7f)<<s;s+=7
        if not x&0x80: break
    return v,i

